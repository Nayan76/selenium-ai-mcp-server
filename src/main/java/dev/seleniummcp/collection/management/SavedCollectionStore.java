package dev.seleniummcp.collection.management;

import dev.seleniummcp.support.ToolFailure;
import java.io.IOException;
import java.nio.ByteBuffer;
import java.nio.channels.FileChannel;
import java.nio.channels.OverlappingFileLockException;
import java.nio.file.FileAlreadyExistsException;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.nio.file.StandardOpenOption;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.regex.Pattern;
import static dev.seleniummcp.collection.management.ManagementInput.*;

final class SavedCollectionStore {
    static final int LIMIT = 32;
    private static final Pattern RECORD = Pattern.compile(UUID.substring(0, UUID.length() - 1) + "\\.json$");
    private static final Pattern STAGE = Pattern.compile("^\\.pending-" + UUID.substring(1, UUID.length() - 1) + "\\.tmp$");
    private static final String LOCK = ".collections.lock";
    private final Path root;
    private final SecureFiles files;

    SavedCollectionStore(Path root, SecureFiles files) {
        this.root = root;
        this.files = files;
    }

    void recover() {
        withLock(() -> { entries(); return null; });
    }

    SavedDefinition save(SavedDefinition record) {
        return withLock(() -> {
            if (entries().size() >= LIMIT) throw new ToolFailure("STORE_LIMIT", "Saved collection storage is full.");
            byte[] bytes = JSON.writeValueAsBytes(record.fields());
            if (bytes.length > MAX_BYTES) throw new ToolFailure("STORE_LIMIT", "The saved collection exceeds the storage limit.");
            Path target = root.resolve(record.id() + ".json");
            Path stage = root.resolve(".pending-" + record.id() + ".tmp");
            if (!Files.notExists(target, LinkOption.NOFOLLOW_LINKS)) throw unavailable();
            files.createPrivateFile(stage);
            try {
                files.checkFile(stage);
                try (var output = FileChannel.open(stage, StandardOpenOption.WRITE, LinkOption.NOFOLLOW_LINKS)) {
                    var data = ByteBuffer.wrap(bytes);
                    while (data.hasRemaining()) output.write(data);
                    output.force(true);
                }
                // Every cooperating process holds this lock, and IDs are generated by the server.
                Files.move(stage, target, StandardCopyOption.ATOMIC_MOVE);
            } finally {
                if (Files.exists(stage, LinkOption.NOFOLLOW_LINKS)) {
                    files.checkFile(stage);
                    Files.delete(stage);
                }
            }
            return record;
        });
    }

    SavedDefinition get(String id) {
        String filename = pattern(id, UUID) + ".json";
        return withLock(() -> {
            Path file = root.resolve(filename);
            if (Files.notExists(file, LinkOption.NOFOLLOW_LINKS)) {
                throw new ToolFailure("SAVED_COLLECTION_NOT_FOUND", "The saved collection was not found.");
            }
            return read(file);
        });
    }

    List<SavedDefinition> list(int limit) {
        return withLock(() -> entries().stream().map(this::read)
                .sorted(Comparator.comparing(SavedDefinition::createdAt).reversed().thenComparing(SavedDefinition::id))
                .limit(limit).toList());
    }

    private SavedDefinition read(Path file) {
        try {
            files.checkFile(file);
            String name = file.getFileName().toString();
            return SavedDefinition.parse(ManagementInput.read(file), name.substring(0, name.length() - 5));
        } catch (IOException | RuntimeException e) {
            throw new ToolFailure("STORE_CORRUPT", "A saved record is unsafe or invalid and requires operator repair.");
        }
    }

    private List<Path> entries() throws IOException {
        var records = new ArrayList<Path>();
        try (var paths = Files.newDirectoryStream(root)) {
            int visited = 0;
            for (Path file : paths) {
                if (++visited > 2 * LIMIT + 1) throw unavailable();
                String name = file.getFileName().toString();
                if (RECORD.matcher(name).matches()) records.add(file);
                else if (STAGE.matcher(name).matches()) {
                    files.checkFile(file);
                    Files.delete(file);
                } else if (!LOCK.equals(name)) throw unavailable();
            }
        }
        if (records.size() > LIMIT) throw new ToolFailure("STORE_LIMIT", "Saved collection storage exceeds its limit.");
        return records;
    }

    private interface Operation<T> { T run() throws IOException; }

    private <T> T withLock(Operation<T> operation) {
        try (var directory = files.guard(root, true)) {
            Path lockPath = root.resolve(LOCK);
            if (Files.notExists(lockPath, LinkOption.NOFOLLOW_LINKS)) {
                try { files.createPrivateFile(lockPath); }
                catch (FileAlreadyExistsException ignored) { /* Another instance initialized the store. */ }
            }
            files.checkFile(lockPath);
            try (var channel = FileChannel.open(lockPath, StandardOpenOption.WRITE, LinkOption.NOFOLLOW_LINKS);
                 var lock = channel.tryLock()) {
                if (lock == null) throw busy();
                return operation.run();
            }
        } catch (OverlappingFileLockException e) {
            throw busy();
        } catch (IOException | SecurityException | LinkageError e) {
            throw unavailable();
        }
    }

    private static ToolFailure busy() { return new ToolFailure("STORE_BUSY", "The saved collection store is busy."); }
    static ToolFailure unavailable() { return new ToolFailure("STORE_UNAVAILABLE", "The saved collection store is unavailable."); }
}
